    (r'\bACCOUNTANT\b|\bCPA\b|\bAUDITOR\b|\bBOOKKEEPER\b', 'FINANCE / INVESTMENT'),
    (r'\bBANKER\b|\bINVEST\b|\bFINANC\b|\bTRADER\b|\bHEDGE\b|\bPORTFOLIO\b', 'FINANCE / INVESTMENT'),
